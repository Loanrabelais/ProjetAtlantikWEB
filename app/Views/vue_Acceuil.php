<h1>Accueil</h1>

<p> Atlantik est une compagnie maritime ancrée sur la côte ouest de la France, dédiée à la desserte régulière des îles du littoral par délégation de service public. Forte de plusieurs contrats avec des conseils généraux, Atlantik assure la continuité territoriale entre le continent et des îles emblématiques telles que Belle-Île-en-Mer, Houat, Groix, Ouessant, Molène, Sein, Bréhat, Batz, Aix ou Yeu.

Notre activité s’articule autour de deux pôles complémentaires : le transport de voyageurs — sûr, confortable et adapté aux besoins locaux — et le transport de fret, garantissant l’acheminement fiable des marchandises essentielles pour la vie insulaire. Alliant expérience maritime, respect des horaires et engagement pour la sécurité, Atlantik relie les hommes, les biens et les territoires pour soutenir le dynamisme des communautés insulaires.
</p>
